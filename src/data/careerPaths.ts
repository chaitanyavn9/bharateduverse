export const getPathById = (id: string) => careerPaths.find((p) => p.id === id);

export const getPathsByUniverse = (universe: string) =>
  careerPaths.filter((p) => p.universe === universe);

export const getPathsByEntryPoint = (entry: string) =>
  careerPaths.filter((p) => p.entryPoints.includes(entry as never));

export const getPathsByStream = (stream: string) =>
  careerPaths.filter((p) => p.streams.includes(stream as never) || p.streams.includes("Any"));
